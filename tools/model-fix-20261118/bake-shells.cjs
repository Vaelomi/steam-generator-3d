function pack(g,signature){
  const p=g.attributes.position,n=g.attributes.normal,index=g.index,vertices=[],indices=[],seen=new Map();
  for(let k=0;k<(index?index.count:p.count);k++){
    const i=index?index.getX(k):k;
    const data=[p.getX(i),p.getY(i),p.getZ(i)].map(x=>Number(x.toFixed(6)))
      .concat([n.getX(i),n.getY(i),n.getZ(i)].map(x=>Number(x.toFixed(5))));
    const key=data.join(",");
    let vertex=seen.get(key);
    if(vertex===undefined){vertex=vertices.length/6;seen.set(key,vertex);vertices.push(...data);}
    indices.push(vertex);
  }
  return {signature,vertices:Buffer.from(new Float32Array(vertices).buffer).toString("base64"),
    indices:Buffer.from(new Uint32Array(indices).buffer).toString("base64"),groups:g.groups};
}
